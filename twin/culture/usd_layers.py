"""USD representation of a culture run: the SDT layer (belief) and the simulator-truth layer, kept apart.

culture_sdt.usda   sublayers scenes/cell01_twin.usda and writes, on Cell 01's semantic plate
                   /World/ExperimentalWorld/Plates/Plate_P17/Wells/<w> (Cell 01 USD mapping, biology-usd-semantic-mapping):
                     * bio:injury / protectiveResponse / glutathione / viability / recoveryProbability as TIME SAMPLES
                       (time code = culture hours) of the posterior mean, plus _p05 / _p95 bounds; bio:uncertainty =
                       half the 90 % interval of V; bio:epistemicStatus = "Inferred" (mapping epistemic_default);
                     * bio:challenge* / rescue* from committed interventions only;
                     * Biological/InterventionHistory/E_<n>: committed (and rejected) dose events with record ids; the
                       committed ones additionally go through Cell 01's own usd_event_bridge.apply_verified_l12_to_usd
                       (sdt:lastVerified* on InterventionHistory);
                     * Biological/ObservationState/t_<hh.h>h: measured features with provenance (image record,
                       calibration record, analysis version); never a latent value (mapping rule 1);
                     * Biological/QualityAndUncertainty: ESS, anomaly / contamination flags;
                     * /World/Evidence/Culture/<run>: claims with model, scope and probability.
culture_truth.usda overs only, no sublayers: /World/SimulatedBiology/Plate_P17/<w> truth:* time samples. Simulator
                   ground truth for audits and for appearance rendering; not part of the SDT.
"""

from __future__ import annotations

import os

from pxr import Sdf, Usd, UsdGeom

PLATE = "/World/ExperimentalWorld/Plates/Plate_P17/Wells"
D, S, B, I_ = Sdf.ValueTypeNames.Double, Sdf.ValueTypeNames.String, Sdf.ValueTypeNames.Bool, Sdf.ValueTypeNames.Int
BELIEF_ATTR = {"I": "bio:injury", "P": "bio:protectiveResponse", "G": "bio:glutathione", "V": "bio:viability",
               "R": "bio:recoveryProbability"}


def _new(path, sublayers=()):
    if os.path.exists(path):
        os.remove(path)
    st = Usd.Stage.CreateNew(path)
    st.GetRootLayer().subLayerPaths = [os.path.relpath(p, os.path.dirname(path)) for p in sublayers]
    UsdGeom.SetStageUpAxis(st, UsdGeom.Tokens.z)
    UsdGeom.SetStageMetersPerUnit(st, 1.0)
    st.SetStartTimeCode(0)
    st.SetEndTimeCode(72)
    st.SetTimeCodesPerSecond(6)
    return st


def _attr(prim, name, typ, value=None, t=None):
    a = prim.GetAttribute(name) or prim.CreateAttribute(name, typ, custom=True)
    if value is not None:
        a.Set(value, t) if t is not None else a.Set(value)
    return a


def write_sdt_layer(path, cell01_scene, run, bridge=None):
    st = _new(path, [cell01_scene])
    st.SetDefaultPrim(st.OverridePrim("/World"))
    st.GetRootLayer().comment = (f"Culture SDT layer of run {run['run_id']} (scenario {run['scenario']}), generated by "
                                 "scripts/run_culture_experiment.py. Belief only; the simulator truth is in culture_truth.usda.")
    for well, hist in run["belief"].items():
        wp = st.OverridePrim(f"{PLATE}/{well}")
        for h in hist:
            t = h["t_h"]
            for k, attr in BELIEF_ATTR.items():
                _attr(wp, attr, D, float(h[k]["mean"]), t)
                _attr(wp, attr + "_p05", D, float(h[k]["p05"]), t)
                _attr(wp, attr + "_p95", D, float(h[k]["p95"]), t)
            _attr(wp, "bio:uncertainty", D, float((h["V"]["p95"] - h["V"]["p05"]) / 2), t)
            _attr(wp, "bio:morphologyRadius_um", D, float(180.0 + 90.0 * h["V"]["mean"]), t)
            _attr(wp, "bio:cultureAge_h", D, float(120.0 + t), t)
        _attr(wp, "bio:epistemicStatus", S, "Inferred")
        _attr(wp, "bio:modelId", S, "M4 Cell 01 surrogate (illustrative) + M6 fitted bright-field observation model; "
                                    "particle filter over state and well coefficients")
        q = st.OverridePrim(f"{PLATE}/{well}/Biological/QualityAndUncertainty")
        for h in hist:
            _attr(q, "sdt:effectiveSampleSize", D, float(h["ess"]), h["t_h"])
        anomaly = run["anomalies"].get(well)
        _attr(wp, "bio:anomalyState", S, anomaly["state"] if anomaly else "none")
        if anomaly:
            _attr(q, "sdt:anomalyActions", Sdf.ValueTypeNames.StringArray, anomaly["actions"])
            _attr(q, "sdt:anomalyDetected_h", D, float(anomaly["t_h"]))
    for n, ev in enumerate(run["interventions"]):
        w = ev["well"]
        wp = st.OverridePrim(f"{PLATE}/{w}")
        e = st.DefinePrim(f"{PLATE}/{w}/Biological/InterventionHistory/E_{n:03d}", "Xform")
        for k, typ, v in (("sdt:eventKind", S, ev["kind"]), ("sdt:abstractUnits", D, float(ev["au"])),
                          ("sdt:time_h", D, float(ev["t_h"])), ("sdt:committed", B, bool(ev["committed"])),
                          ("sdt:sourceRecord", S, str(ev["record"])), ("sdt:reasons", S, "; ".join(ev["reasons"]))):
            _attr(e, k, typ, v)
        if ev["committed"]:
            pre = "bio:" + ev["kind"]
            _attr(wp, pre + "Agent", S, f"abstract_{ev['kind']}_reagent")
            _attr(wp, pre + "Dose_au", D, float(ev["au"]))
            _attr(wp, pre + "Time_h", D, float(ev["t_h"]))
    for well, obs in run["observations"].items():
        for o in obs:
            p = st.DefinePrim(f"{PLATE}/{well}/Biological/ObservationState/t_{o['t_h']:05.1f}h".replace(".", "_"), "Xform")
            f = o.get("features") or {}
            for k, typ, v in (("obs:time_h", D, float(o["t_h"])), ("obs:accepted", B, bool(o["accepted"])),
                              ("obs:radius_um", D, f.get("radius_um")), ("obs:coreOpticalDensity", D, f.get("core_od")),
                              ("obs:debrisCount", I_, f.get("debris")), ("obs:haze", D, f.get("haze")),
                              ("obs:source", S, "L17 bright-field 4x image, twin/culture/optics.py analyse() v1"),
                              ("obs:imageRecordId", S, o.get("record")), ("obs:calibrationRecordId", S, o.get("calibration")),
                              ("obs:latentInjuryHidden", B, True), ("obs:reason", S, o.get("reason"))):
                if v is not None:
                    _attr(p, k, typ, v)
    ev = st.DefinePrim(f"/World/Evidence/Culture/{run['run_id']}", "Xform")
    _attr(ev, "sdt:scenario", S, run["scenario"])
    for i, c in enumerate(run["claims"]):
        cp = st.DefinePrim(f"/World/Evidence/Culture/{run['run_id']}/Claim_{i:02d}", "Xform")
        for k, typ, v in (("claim:proposition", S, c["proposition"]), ("claim:probability", D, float(c["probability"])),
                          ("claim:model", S, c["model"]), ("claim:scope", S, c["scope"]),
                          ("claim:status", S, c["status"])):
            _attr(cp, k, typ, v)
    st.GetRootLayer().Save()
    applied = []
    if bridge is not None:      # Cell 01's own bridge stamps the committed L12 events onto InterventionHistory
        for rec in run["committed_records"]:
            res = bridge.apply_verified_l12_to_usd(__import__("pathlib").Path(path), rec, save=True)
            applied.append(dict(well=rec["designator"]["well_id"], applied=res["applied"], reasons=res["reasons"]))
    return applied


def write_truth_layer(path, run):
    st = _new(path)
    st.GetRootLayer().comment = "Simulator ground truth (twin/culture/model.py CultureWorld). NOT part of the SDT."
    root = UsdGeom.Xform.Define(st, "/World/SimulatedBiology/Plate_P17").GetPrim()
    _attr(root, "sdt:role", S, "simulator ground truth: hidden from the robot and the SDT; for audits and appearance")
    for well, hist in run["truth"].items():
        p = UsdGeom.Xform.Define(st, f"/World/SimulatedBiology/Plate_P17/{well}").GetPrim()
        for h in hist[::2]:                                  # 0.5 h samples
            for k in ("I", "P", "G", "V", "R", "B"):
                _attr(p, f"truth:{k}", D, float(h[k]), h["t_h"])
            _attr(p, "truth:radius_um", D, float(h["radius_um"]), h["t_h"])
            _attr(p, "truth:core_od", D, float(h["core_od"]), h["t_h"])
    st.GetRootLayer().Save()
